#!/usr/bin/env node
// Regenerates public/data/ai-snapshot.json with a live Claude run.
//
//   ANTHROPIC_API_KEY=sk-ant-... node scripts/build-ai-snapshot.mjs [--dry-run]
//
// Uses the same prompts, model and tool versions as api/claude.js, for the
// bundled watchlist and the sample portfolio. Costs real API credits (two
// requests with web search). --dry-run prints the prompts and exits.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import Anthropic from "@anthropic-ai/sdk";

import { WATCHLIST_STOCKS } from "../src/data.js";
import { SAMPLE_PORTFOLIO } from "../src/portfolio.js";
import { buildNewsPrompt, buildAdvicePrompt, extractJson, normalizeNews } from "../src/ai/prompts.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.resolve(here, "../public/data/ai-snapshot.json");
const MODEL = "claude-opus-5-5";
const BUDGET = 50000;

const tickers = Object.keys(WATCHLIST_STOCKS);
const newsPrompt = buildNewsPrompt(tickers);
const advicePrompt = buildAdvicePrompt(SAMPLE_PORTFOLIO, BUDGET);

if (process.argv.includes("--dry-run")) {
  console.log("--- news prompt ---\n" + newsPrompt + "\n\n--- advice prompt ---\n" + advicePrompt);
  process.exit(0);
}

if (!process.env.ANTHROPIC_API_KEY) {
  console.error("ANTHROPIC_API_KEY is not set. Nothing was written.");
  process.exit(1);
}

const client = new Anthropic();

async function ask(prompt) {
  const messages = [{ role: "user", content: prompt }];
  let response;
  for (let attempt = 0; attempt <= 3; attempt++) {
    response = await client.beta.messages.create({
      model: MODEL,
      max_tokens: 16000,
      output_config: { effort: "medium" },
      tools: [{ type: "web_search_20260209", name: "web_search", max_uses: 5 }],
      betas: ["server-side-fallback-2026-07-01"],
      fallbacks: "default",
      messages,
    });
    if (response.stop_reason !== "pause_turn") break;
    messages.push({ role: "assistant", content: response.content });
  }
  if (response.stop_reason === "refusal") throw new Error("Request was declined (stop_reason=refusal)");
  const text = response.content.filter(b => b.type === "text").map(b => b.text).join("");
  const parsed = extractJson(text);
  if (!parsed) throw new Error(`No JSON in response (stop_reason=${response.stop_reason})`);
  return { parsed, model: response.model };
}

try {
  const generatedAt = new Date().toISOString();
  console.log("Fetching news analysis...");
  const news = await ask(newsPrompt);
  console.log("Fetching monthly advice...");
  const advice = await ask(advicePrompt);

  const snapshot = {
    generatedAt,
    source: "live snapshot",
    model: news.model,
    note: `Generated by scripts/build-ai-snapshot.mjs with ${news.model} and web search.`,
    tickers,
    news: normalizeNews(news.parsed, "snap", generatedAt),
    advice: advice.parsed,
  };
  fs.writeFileSync(OUT, JSON.stringify(snapshot, null, 2) + "\n");
  console.log(`Wrote ${path.relative(process.cwd(), OUT)} (${snapshot.news.articles.length} articles).`);
} catch (err) {
  if (err instanceof Anthropic.APIError) {
    console.error(`Claude API error ${err.status}: ${err.constructor.name}`);
  } else {
    console.error(err.message || err);
  }
  process.exit(1);
}
